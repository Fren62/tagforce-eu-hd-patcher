"""Loads the corrections to the card texts and applies them to the texts read from cardinfo_xxx.ehp: data/card_corrections.json for Italian
(generated by generate_italian_corrections.py), data/card_corrections_<language>.json (fr, de, es, en) for the others.
Used by cardprops.load / cardnames.names: every generated image (HD cards, small cards, names) uses the corrected texts.
To use the original texts: environment variable TF1_NO_CORRECTIONS=1."""
import json, os

_DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
_CACHE = {}


def _file(language):
    return os.path.join(_DATA, 'card_corrections.json' if language == 'it' else f'card_corrections_{language}.json')


def table(language='it'):
    if language not in _CACHE:
        _CACHE[language] = {}
        if not os.environ.get('TF1_NO_CORRECTIONS') and os.path.exists(_file(language)):
            _CACHE[language] = {int(k): v for k, v in json.load(open(_file(language), encoding='utf-8')).items()}
    return _CACHE[language]


def card(card_id, field, text, language='it'):
    """Corrected text of `field` ('name' or 'desc') of the card, or `text` if there are no corrections for that language."""
    return table(language).get(card_id, {}).get(field, text)
